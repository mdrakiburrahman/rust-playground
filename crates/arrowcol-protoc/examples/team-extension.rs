//! Example second plugin: consume the generated SDK, not its transport internals.
use std::io::{Read, Write};

use arrowcol_protoc::{CodeGeneratorRequest, CodeGeneratorResponse, GeneratedFile};
use prost::Message;

fn main() -> arrowcol_protoc::Result<()> {
    let mut bytes = Vec::new();
    std::io::stdin().take(64 * 1024 * 1024 + 1).read_to_end(&mut bytes)?;
    if bytes.len() > 64 * 1024 * 1024 {
        return Err("plugin input exceeds 64 MiB".into());
    }
    let request = CodeGeneratorRequest::decode(bytes.as_slice())?;
    let response = if request.file_to_generate.len() != 1 {
        CodeGeneratorResponse {
            error: Some("example expects one table".to_owned()),
            file: Vec::new(),
        }
    } else {
        CodeGeneratorResponse {
            error: None,
            file: vec![GeneratedFile {
                name: Some("typescript/team.ts".to_owned()),
                content: Some(
                    "// Generated by a separate team plugin; the SDK owns all Arrowcol mappings.\n\
                     import { createDoPutPlan, recordBatch } from './src/index.js';\n\
                     export function planTeamTelemetry(rows: Parameters<typeof recordBatch>[0]) {\n\
                     \x20 return createDoPutPlan(recordBatch(rows));\n\
                     }\n"
                    .to_owned(),
                ),
            }],
        }
    };
    std::io::stdout().write_all(&response.encode_to_vec())?;
    Ok(())
}
